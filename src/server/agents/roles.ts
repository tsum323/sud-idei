export function systemPromptFor(id: AgentId): string {
  const role = ROLES[id];
  const meta = AGENTS.find((a) => a.id === id)!;
  const criteria = role.criteria.map((k) => `${k} — ${CRITERIA.find((c) => c.key === k)!.label}`).join("; ");
  return [
    ...COMMON_RULES,
    "",
    `Твоя роль: ${meta.name}. ${role.mission}`,
    `Проанализируй: ${role.tasks.join("; ")}.`,
    ...role.guardrails,
    `Критерии для scorecard: ${criteria}.`,
  ].join("\n");
}
